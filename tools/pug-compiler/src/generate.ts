/**
 * Intermediate representation → TypeScript module exporting a
 * `TProjectionTemplate<TData, TNodes>` (ADR-22, ADR-26).
 *
 * For each fragment F the module holds:
 *   - `$eF(...)` — evaluator: every dynamic value of F, from its parameters;
 *   - `$cF(...)` — create: builds the DOM of F from the values;
 *   - `$sF(…)`   — setup: locates the dynamic nodes of F in an existing DOM;
 *   - `$pF(n, …)` — project: guarded mutations of the located nodes;
 *   - `$kF(...)` — for an item: its key, computed without the index.
 * The parameters of F are `$data` then the scope variables it receives.
 */
import type { TElement, TFragment, TList, TLocal, TNode, TSwitch, TTemplateIR } from "./ir";

export type TGenerateOptions = {
  /** Exported name of the template, e.g. `CartItemsTemplate`. */
  readonly name: string;
  /** Name of the source file, quoted in the header. */
  readonly source: string;
  /** Module importing `ProjectionList`, `ProjectionSwitch` and `TProjectionTemplate`. */
  readonly runtime: string;
};

const q = (value: string): string => JSON.stringify(value);

class Writer {
  readonly #lines: string[] = [];
  #depth = 0;
  line(text = ""): this {
    this.#lines.push(text === "" ? "" : "  ".repeat(this.#depth) + text);
    return this;
  }
  open(text: string): this {
    this.line(text);
    this.#depth++;
    return this;
  }
  close(text = "}"): this {
    this.#depth--;
    return this.line(text);
  }
  toString(): string {
    return this.#lines.join("\n") + "\n";
  }
}

export function generate(ir: TTemplateIR, { name, source, runtime }: TGenerateOptions): string {
  const w = new Writer();
  const frag = (index: number): TFragment => ir.fragments[index]!;
  let tmp = 0;
  const fresh = (prefix: string): string => `${prefix}${tmp++}`;

  /** Parameter declarations of a fragment. */
  const signature = (f: TFragment): string => ["$data: TData", ...f.params.map((p) => `${p.id}: ${p.type}`)].join(", ");
  /** Arguments a parent (evaluated as `$v`) passes to a child for the variables it inherits. */
  const inherited = (parent: TFragment, child: TFragment): string[] => {
    const own = child.kind === "item" ? child.params.slice(0, -2) : child.params;
    return ["$data", ...own.map((p) => (parent.locals.some((l) => l.id === p.id) ? `$v[${q(p.id)}]` : p.id))];
  };
  const inheritedTypes = (child: TFragment): string =>
    `[${["TData", ...(child.kind === "item" ? child.params.slice(0, -2) : child.params).map((p) => p.type)].join(", ")}]`;

  // ── Header ───────────────────────────────────────────────────────────
  w.line("/**")
    .line(` * Generated by tools/pug-compiler from ${source} — do not edit.`)
    .line(" * Recompile with: pnpm pug")
    .line(" */")
    .line("/* eslint-disable */");
  const runtimeImports = [...(ir.usesList ? ["ProjectionList"] : []), ...(ir.usesSwitch ? ["ProjectionSwitch"] : []), "type TProjectionTemplate"];
  w.line(`import { ${runtimeImports.join(", ")} } from ${q(runtime)};`).line();
  w.line(`/** Data of the template: the output of \`select\`, or the result of the Query. */`);
  w.line(`export type T${name}Data = ${ir.dataType ?? "undefined"};`);
  w.line(`type TData = T${name}Data;`);
  if (ir.usesList) w.line("type $Item<T> = T extends readonly (infer I)[] ? I : never;");
  w.line(`const $text = (v: unknown): string => (v === null || v === undefined ? "" : String(v));`);
  w.open("const $attr = (el: Element, name: string, v: unknown): void => {")
    .open("if (v === false || v === null || v === undefined) {")
    .line("if (el.hasAttribute(name)) el.removeAttribute(name);")
    .line("return;")
    .close()
    .line(`const s = v === true ? "" : String(v);`)
    .line("if (el.getAttribute(name) !== s) el.setAttribute(name, s);")
    .close("};");

  // ── Evaluators and keys ──────────────────────────────────────────────
  const declareFields = (fields: ReadonlySet<string>): void => {
    if (fields.size > 0) w.line(`const { ${[...fields].sort().join(", ")} } = $data;`);
  };
  const declareLocals = (locals: readonly TLocal[]): void => {
    for (const local of locals) w.line(`const ${local.id} = ${local.code};`);
  };
  for (const f of ir.fragments) {
    w.line();
    w.open(`const $e${f.index} = (${signature(f)}) => {`);
    const fields = new Set(f.fields);
    for (const local of f.locals) for (const field of local.fields) fields.add(field);
    declareFields(fields);
    declareLocals(f.locals);
    const entries = [...f.slots.map((s) => `${s.id}: ${s.code}`), ...f.locals.map((l) => `${q(l.id)}: ${l.id}`)];
    if (entries.length === 0) w.line("return {};");
    else {
      w.open("return {");
      entries.forEach((e, i) => w.line(e + (i < entries.length - 1 ? "," : "")));
      w.close("};");
    }
    w.close("};");
    if (f.key !== null) {
      const params = f.params.slice(0, -1);
      w.open(`const $k${f.index} = (${["$data: TData", ...params.map((p) => `${p.id}: ${p.type}`)].join(", ")}): string => {`);
      declareFields(f.key.fields);
      declareLocals(f.key.locals);
      w.line(`return $text(${f.key.code});`);
      w.close("};");
    }
  }

  // ── Create ───────────────────────────────────────────────────────────
  /** Appends the creation of `nodes` to `parent`, inside the create of `f`. */
  const createNodes = (f: TFragment, nodes: readonly TNode[], parent: string): void => {
    for (const node of nodes) {
      switch (node.kind) {
        case "text":
          w.line(`${parent}.append(document.createTextNode(${q(node.value)}));`);
          break;
        case "dyntext":
          w.line(`${parent}.append(document.createTextNode($v.${node.slot}));`);
          break;
        case "element":
          w.line(`${parent}.append(${createElement(f, node)});`);
          break;
        case "switch":
          w.line(`${parent}.append(ProjectionSwitch.create($v.${node.slot}, ${branchCreate(f, node, `$v.${node.slot}`)}));`);
          break;
        case "list":
          w.line(`${parent}.append(...${listItems(f, node)});`);
          break;
      }
    }
  };
  const listItems = (f: TFragment, node: TList): string =>
    `$v.${node.slot}.map(($it, $i) => $c${node.body.index}(${[...inherited(f, node.body), "$it", "$i"].join(", ")}))`;
  const branchCreate = (f: TFragment, node: TSwitch, branch: string): string => {
    let code = "null";
    for (let i = node.branches.length - 1; i >= 0; i--) {
      const b = node.branches[i]!;
      code = `${branch} === ${i} ? $c${b.index}(${inherited(f, b).join(", ")}) : ${code}`;
    }
    return code;
  };
  /** Declares the element and its content; returns its variable. */
  const createElement = (f: TFragment, el: TElement): string => {
    const v = fresh("$n");
    w.line(`const ${v} = document.createElement(${q(el.tag)});`);
    for (const attr of el.attrs) w.line(`${v}.setAttribute(${q(attr.name)}, ${q(attr.value === true ? "" : attr.value)});`);
    for (const attr of el.key === null ? el.dyn : [el.key, ...el.dyn]) w.line(`$attr(${v}, ${q(attr.name)}, $v.${attr.slot});`);
    if (el.text !== null) w.line(`${v}.textContent = ${"value" in el.text ? q(el.text.value) : `$v.${el.text.slot}`};`);
    else createNodes(f, el.children, v);
    return v;
  };
  for (const f of ir.fragments) {
    const returns = f.kind === "item" ? "HTMLElement" : "DocumentFragment";
    w.line();
    w.open(`function $c${f.index}(${signature(f)}): ${returns} {`);
    w.line(`const $v = $e${f.index}(${["$data", ...f.params.map((p) => p.id)].join(", ")});`);
    if (f.kind === "item") {
      tmp = 0;
      const root = createElement(f, f.nodes[0] as TElement);
      w.line(`return ${root};`);
    } else {
      tmp = 0;
      w.line("const $f = document.createDocumentFragment();");
      createNodes(f, f.nodes, "$f");
      w.line("return $f;");
    }
    w.close();
  }

  // ── Setup ────────────────────────────────────────────────────────────
  const needsRef = (el: TElement): boolean => el.dyn.length > 0 || (el.text !== null && "slot" in el.text);
  const needsSetup = (node: TNode): boolean => {
    switch (node.kind) {
      case "text":
        return false;
      case "element":
        return needsRef(node) || node.children.some(needsSetup);
      default:
        return true;
    }
  };
  /** Located refs of the fragment being set up: property → local variable. */
  let refs: [string, string][] = [];
  /** Property of each located node in the nodes of its fragment, for project. */
  const refOf = new Map<TNode, string>();
  const setupSequence = (nodes: readonly TNode[], first: string): void => {
    const last = nodes.reduce((acc, n, i) => (needsSetup(n) ? i : acc), -1);
    if (last < 0) return;
    const cursor = fresh("$c");
    w.line(`let ${cursor}: ChildNode | null = ${first};`);
    nodes.forEach((node, i) => {
      if (i > last) return;
      const advance = i < last;
      switch (node.kind) {
        case "text":
          break;
        case "dyntext": {
          const t = fresh("$t");
          w.line(`const ${t} = ${cursor} as Text;`);
          refs.push([t.slice(1), t]);
          refOf.set(node, t.slice(1));
          break;
        }
        case "element":
          if (needsSetup(node)) {
            const v = fresh("$n");
            w.line(`const ${v} = ${cursor} as HTMLElement;`);
            setupElement(node, v);
          }
          break;
        case "switch": {
          w.line(`const $${node.id} = new ProjectionSwitch<${switchNodes(node)}>(${cursor}, $w${node.id.slice(1)});`);
          refs.push([node.id, `$${node.id}`]);
          if (advance) w.line(`${cursor} = $${node.id}.end.nextSibling;`);
          return;
        }
        case "list":
          throw new Error("unreachable: a list is the only child of its container");
      }
      if (advance) w.line(`${cursor} = ${cursor}!.nextSibling;`);
    });
  };
  const setupElement = (el: TElement, v: string): void => {
    if (needsRef(el)) {
      refs.push([v.slice(1), v]);
      refOf.set(el, v.slice(1));
    }
    if (el.text !== null) return;
    const only = el.children[0];
    if (el.children.length === 1 && only !== undefined && only.kind === "list") setupList(only, v);
    else setupSequence(el.children, `${v}.firstChild`);
  };
  const setupList = (node: TList, container: string): void => {
    const body = node.body;
    const holder = `$${node.id}`;
    const item = body.params[body.params.length - 2]!.type;
    w.line(
      `const ${holder} = { $: undefined as unknown as ${inheritedTypes(body)}, list: undefined as unknown as ProjectionList<${item}, ReturnType<typeof $s${body.index}>> };`
    );
    w.open(`${holder}.list = new ProjectionList<${item}, ReturnType<typeof $s${body.index}>>(${container}, {`)
      .line(`keyAttr: ${q(body.key!.attr)},`)
      .line(`key: ($it) => $k${body.index}(...${holder}.$, $it),`)
      .line(`create: ($it, $i) => $c${body.index}(...${holder}.$, $it, $i),`)
      .line(`setup: $s${body.index},`)
      .line(`update: ($n, $it, $i) => $p${body.index}($n, ...${holder}.$, $it, $i)`)
      .close("});");
    refs.push([node.id, holder]);
  };
  const switchNodes = (node: TSwitch): string => [...node.branches.map((b) => `ReturnType<typeof $s${b.index}>`), "undefined"].join(" | ");
  const returnRefs = (): void => {
    if (refs.length === 0) w.line("return {};");
    else w.line(`return { ${refs.map(([k, v]) => (k === v ? k : `${k}: ${v}`)).join(", ")} };`);
  };

  // Branch setup dispatchers, one per switch.
  const switches: TSwitch[] = [];
  const collect = (nodes: readonly TNode[]): void => {
    for (const n of nodes) {
      if (n.kind === "switch") switches.push(n);
      if (n.kind === "element") collect(n.children);
    }
  };
  for (const f of ir.fragments) collect(f.nodes);

  for (const f of ir.fragments) {
    w.line();
    refs = [];
    tmp = 0;
    if (f.kind === "root") {
      w.open(`function $s${f.index}($container: HTMLElement) {`);
      const only = f.nodes[0];
      if (f.nodes.length === 1 && only !== undefined && only.kind === "list") setupList(only, "$container");
      else setupSequence(f.nodes, "$container.firstChild");
    } else if (f.kind === "item") {
      w.open(`function $s${f.index}($el: HTMLElement) {`);
      setupElement(f.nodes[0] as TElement, "$el");
    } else {
      w.open(`function $s${f.index}($first: ChildNode | null) {`);
      setupSequence(f.nodes, "$first");
    }
    returnRefs();
    w.close();
  }
  for (const s of switches) {
    const n = s.id.slice(1);
    let code = "undefined";
    for (let i = s.branches.length - 1; i >= 0; i--) code = `$b === ${i} ? $s${s.branches[i]!.index}($f) : ${code}`;
    w.line(`const $w${n} = ($b: number, $f: ChildNode | null) => ${code};`);
  }

  // ── Project ──────────────────────────────────────────────────────────
  const projectNodes = (f: TFragment, nodes: readonly TNode[]): void => {
    for (const node of nodes) {
      switch (node.kind) {
        case "text":
          break;
        case "dyntext": {
          const t = refOf.get(node)!;
          w.line(`if ($n.${t}.data !== $v.${node.slot}) $n.${t}.data = $v.${node.slot};`);
          break;
        }
        case "element":
          projectElement(f, node);
          break;
        case "switch": {
          const n = node.id.slice(1);
          w.line(`const $b${n} = $v.${node.slot};`);
          w.line(`const $m${n} = $n.${node.id}.project($b${n}, ($b) => ${branchCreate(f, node, "$b")}, $w${n});`);
          node.branches.forEach((br, i) => {
            const args = inherited(f, br).join(", ");
            w.line(`${i === 0 ? "if" : "else if"} ($b${n} === ${i}) $p${br.index}($m${n} as ReturnType<typeof $s${br.index}>, ${args});`);
          });
          break;
        }
        case "list":
          w.line(`$n.${node.id}.$ = [${inherited(f, node.body).join(", ")}];`);
          w.line(`$n.${node.id}.list.reconcile($v.${node.slot});`);
          break;
      }
    }
  };
  const projectElement = (f: TFragment, el: TElement): void => {
    if (!needsSetup(el)) return;
    const name = refOf.get(el);
    if (name !== undefined) {
      for (const attr of el.dyn) w.line(`$attr($n.${name}, ${q(attr.name)}, $v.${attr.slot});`);
      if (el.text !== null && "slot" in el.text) {
        w.line(`if ($n.${name}.textContent !== $v.${el.text.slot}) $n.${name}.textContent = $v.${el.text.slot};`);
      }
    }
    if (el.text === null) projectNodes(f, el.children);
  };
  for (const f of ir.fragments) {
    w.line();
    w.open(`function $p${f.index}($n: ReturnType<typeof $s${f.index}>, ${signature(f)}): void {`);
    w.line(`const $v = $e${f.index}(${["$data", ...f.params.map((p) => p.id)].join(", ")});`);
    projectNodes(f, f.nodes);
    w.close();
  }

  // ── Export ───────────────────────────────────────────────────────────
  w.line();
  w.open(`export const ${name}: TProjectionTemplate<TData, ReturnType<typeof $s0>> = {`)
    .line("create: (data) => $c0(data),")
    .line("setup: (container) => $s0(container),")
    .line("project: (nodes, data) => $p0(nodes, data)")
    .close("};");
  return w.toString();
}
